/**
 * @module O 内容工具箱
 *
 * distribution.enemy 投影器——把 Resource Graph 中的 distribution.enemy 节点反向
 * 投影回 oblivions/gamedata/enemy_pool.php 的 tide 桶形态。
 *
 * 设计意图（执行案 06-P5 §4.7.2 / §4.2.1 / §4.3.2）：
 * - distribution.enemy 节点采用 DistributionRule 统一模型（id=`${tide}:${enemy_type}`，
 *   data 含 'subject.enemy_type' / 'selector.tides' / 'placement.count' 等点号 key）。
 * - 投影回 enemy_pool.php 时需把统一模型反向派生为原始 `{enemy_type, count}` entry
 *   形态，按 tide 桶分组（shallow / deep / abyss）。
 * - tide 桶 key 顺序固定为 shallow → deep → abyss（对齐原文件 + J-2 潮汐区主键枚举）。
 * - 桶内条目顺序按节点数组顺序保留（vuedraggable 拖拽后写入图，投影时按图顺序输出）。
 * - P5-2 改用 generatePhpFile API：文件头注入 `// AUTO-GENERATED FROM ...` 注释、
 *   模块标签与 sectionTitle 由 schema.projectionTargets 派生，不再使用硬编码文件头。
 *
 * 反向投影字段映射：
 *   - 节点 id `${tide}:${enemy_type}`         → 拆分得 tide + enemy_type（与 data 字段冗余校验）
 *   - data['subject.enemy_type']               → entry.enemy_type（数字，与原文件对齐）
 *   - data['placement.count']                  → entry.count（int 或 [min,max] 区间）
 *   - data['selector.tides'][0]                → tide 桶 key（与 id 拆分得 tide 一致）
 *
 * 注释漂移修复（执行案 §4.7.3）：原 enemy_pool.php 有手写漂移注释（如
 * "废铁史莱姆 3-5 个" 但实际 count 是 [1,1]）。本投影器不保留旧注释——
 * O-5 写路径以代码权威派生数据，旧注释视为已漂移不复活。新增条目无注释。
 *
 * 边界：
 * - 节点 data 缺失字段时使用默认值（count=1，tide 从 id 拆分）
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.1：当前运行时契约每条规则只有一个 tide）
 * - 节点 id 不匹配 idPattern 时跳过该节点（不写入任何桶）
 * - 空桶也输出（如 abyss 桶即使无条目也输出 `[]`）——与原文件 3 桶结构对齐
 *
 * 集成：
 * - adapter-registry.serializeNodes 路由到本投影器（当 kind='distribution.enemy' 时）
 * - BuildView 在发布前调用本投影器生成 PublishableFile
 */

import { generatePhpFile, type PhpValue } from '../../shared/serializer/php-codegen';
import type { ResourceNode } from '../../graph/types';
import type { SerializedPhpFile } from '../../adapters/php-adapter';

/** 目标文件路径（工作区相对路径） */
const ENEMY_POOL_FILE_PATH = 'oblivions/gamedata/enemy_pool.php';

/** 作者资源 YAML 路径——用于 AUTO-GENERATED 注释 */
const ENEMY_POOL_AUTHOR_SOURCE = 'oblivions/content/distributions/enemy-pool.yaml';

/** tide 桶固定顺序——与 enemy_pool.php 文件顺序 + J-2 潮汐区主键枚举对齐 */
const TIDE_ORDER = ['shallow', 'deep', 'abyss'] as const;
type TideBucket = (typeof TIDE_ORDER)[number];

/** distribution.enemy 节点 id 正则——与 schema idPattern 对齐 */
const DISTRIBUTION_ENEMY_ID_PATTERN = /^(shallow|deep|abyss):[1-9]\d*$/;

/** distribution.enemy 节点 data 期望形态 */
interface DistributionEnemyData {
  'subject.enemy_type': number | string;
  'selector.tides': string[];
  'selector.regions': string[];
  'selector.excludeEntrance': boolean;
  'selector.excludeExit': boolean;
  'selector.excludeOccupied': boolean;
  'placement.count': number | [number, number];
}

/**
 * 把 distribution.enemy 节点投影回 enemy_pool.php 形态。
 *
 * @param nodes distribution.enemy 节点数组（顺序保留为桶内条目顺序）
 * @returns 单个 SerializedPhpFile（filePath 指向 oblivions/gamedata/enemy_pool.php）
 *
 * @throws 当 selector.tides 长度 > 1 时抛错（运行时契约每条规则只有一个 tide）
 */
export function projectEnemyPool(nodes: ResourceNode[]): SerializedPhpFile[] {
  const buckets = buildTideBuckets(nodes);
  const content = generatePhpFile(buckets, {
    module: 'E 游戏逻辑',
    sectionTitle: 'Oblivions NPC 敌人生成池',
    autoGeneratedFrom: ENEMY_POOL_AUTHOR_SOURCE,
  });
  return [{ filePath: ENEMY_POOL_FILE_PATH, content }];
}

/**
 * 把 distribution.enemy 节点按 tide 桶分组，重建为 enemy_pool.php 字典形态。
 *
 * 输出形态：`{ shallow: [...], deep: [...], abyss: [...] }`，每个桶是索引数组，
 * 数组元素是 `{enemy_type, count}` 关联数组。
 *
 * tide 桶 key 顺序固定为 shallow → deep → abyss（即使某桶为空也输出空数组），
 * 与原文件 3 桶结构对齐。
 *
 * 桶内条目顺序按节点数组顺序保留——vuedraggable 拖拽后节点顺序变化，投影器
 * 按图顺序输出，保证用户拖拽意图传递到文件。
 */
function buildTideBuckets(nodes: ResourceNode[]): PhpValue {
  // 初始化 3 个桶为空数组（按 TIDE_ORDER 顺序）
  const buckets: Record<TideBucket, Array<{ enemy_type: number | string; count: number | [number, number] }>> = {
    shallow: [],
    deep: [],
    abyss: [],
  };

  for (const node of nodes) {
    const parsed = parseDistributionEnemyNode(node);
    if (parsed === null) continue;
    buckets[parsed.tide].push({ enemy_type: parsed.enemyType, count: parsed.count });
  }

  // 输出为 PhpValue 字典——保留 TIDE_ORDER 顺序
  const result: Record<string, PhpValue> = {};
  for (const tide of TIDE_ORDER) {
    result[tide] = buckets[tide].map((entry) => ({
      enemy_type: entry.enemy_type,
      count: entry.count,
    }));
  }
  return result;
}

/**
 * 解析单个 distribution.enemy 节点，提取 tide + enemy_type + count。
 *
 * 校验：
 * - 节点 id 必须匹配 `^(shallow|deep|abyss):[1-9]\d*$`，否则返回 null（跳过）
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.1 运行时契约）
 * - selector.tides[0] 必须与 id 拆分得的 tide 一致（冗余校验，防止数据漂移）
 * - count 默认 1（与 schema default 对齐）
 *
 * enemy_type 类型：原文件 enemy_pool.php 用数字（`'enemy_type' => 1`），
 * 投影器保留数字类型——通过 data['subject.enemy_type'] 优先取值，缺失时从 id 拆分。
 *
 * @returns 解析后的 { tide, enemyType, count }；非法节点返回 null
 */
function parseDistributionEnemyNode(
  node: ResourceNode,
): { tide: TideBucket; enemyType: number | string; count: number | [number, number] } | null {
  const idMatch = DISTRIBUTION_ENEMY_ID_PATTERN.exec(node.id);
  if (!idMatch) return null;

  const tideFromId = idMatch[1] as TideBucket;
  const enemyTypeFromId = idMatch[2] ?? '';
  if (!enemyTypeFromId) return null;

  const data = node.data as Partial<DistributionEnemyData> | null;
  if (data === null || typeof data !== 'object' || Array.isArray(data)) {
    // data 非法：用 id 拆分得的最小信息构造 entry
    return { tide: tideFromId, enemyType: Number(enemyTypeFromId), count: 1 };
  }

  // selector.tides 校验——当前运行时契约每条规则只有一个 tide
  const tides = data['selector.tides'];
  if (Array.isArray(tides) && tides.length > 1) {
    throw new Error(
      `distribution.enemy 投影失败：节点 ${node.id} 的 selector.tides 长度为 ${tides.length}，` +
        `当前运行时契约每条规则只有一个 tide（执行案 §4.2.1）`,
    );
  }

  // tide 一致性校验——id 拆分为主，selector.tides 字段在投影回写时被修正
  // 不抛错——投影器是写路径，应以 id 主键为准
  const tideFromSelector = Array.isArray(tides) && tides.length === 1 ? tides[0] : undefined;
  if (
    tideFromSelector !== undefined &&
    tideFromSelector !== tideFromId &&
    (tideFromSelector === 'shallow' || tideFromSelector === 'deep' || tideFromSelector === 'abyss')
  ) {
    // 数据漂移：以 id 拆分为主
  }

  // enemy_type：优先用 data['subject.enemy_type']，缺失时从 id 拆分
  // 保留原类型（number 或 string）——data 中若是 number 则输出数字，若是 string
  // 但内容是数字字符串，objectToPhp 会按数字 key 处理（不加引号），实际仍输出数字
  const enemyTypeFromData = data['subject.enemy_type'];
  let finalEnemyType: number | string;
  if (typeof enemyTypeFromData === 'number') {
    finalEnemyType = enemyTypeFromData;
  } else if (typeof enemyTypeFromData === 'string' && enemyTypeFromData !== '') {
    // data 中是字符串（如 '1'）——转为 number 输出，对齐原文件数字 key
    const num = Number(enemyTypeFromData);
    finalEnemyType = Number.isFinite(num) ? num : enemyTypeFromData;
  } else {
    finalEnemyType = Number(enemyTypeFromId);
  }

  // count 默认 1（与 schema default 对齐）
  const countRaw = data['placement.count'];
  let count: number | [number, number];
  if (Array.isArray(countRaw) && countRaw.length === 2) {
    count = [Number(countRaw[0]), Number(countRaw[1])];
  } else if (typeof countRaw === 'number' && Number.isFinite(countRaw)) {
    count = countRaw;
  } else {
    count = 1;
  }

  return { tide: tideFromId, enemyType: finalEnemyType, count };
}
