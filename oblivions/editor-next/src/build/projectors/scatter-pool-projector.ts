/**
 * @module O 内容工具箱
 *
 * distribution.scatter 投影器——把 Resource Graph 中的 distribution.scatter 节点
 * 反向投影回 oblivions/gamedata/scatter_pool.php 的 tide × phase 矩阵形态。
 *
 * 设计意图（执行案 §4.7.2 / §4.2.2）：
 * - distribution.scatter 节点采用 DistributionRule 统一模型
 *   （id=`${tide}:${phase}:${item_id}`，data 含 'subject.item_id' / 'selector.tides' /
 *   'phase' / 'placement.rate' / 'placement.count' 等点号 key）。
 * - 投影回 scatter_pool.php 时需把统一模型反向派生为原始 `{item_id, count, rate}`
 *   entry 形态，按 tide × phase 矩阵分组（3 tide × 2 phase = 6 列表）。
 * - phase 字段映射：节点 data.phase='game_init' → 文件 key 'initial'；
 *   节点 data.phase='day_refresh' → 文件 key 'refresh'。
 * - tide 桶 key 顺序固定为 shallow → deep → abyss（对齐原文件 + J-2 潮汐区主键枚举）。
 * - phase 顺序固定为 initial → refresh（对齐原文件 + 运行时枚举）。
 * - 列表内条目顺序按节点数组顺序保留（vuedraggable 拖拽后写入图，投影时按图顺序输出）。
 *
 * 反向投影字段映射：
 *   - 节点 id `${tide}:${phase}:${item_id}`  → 拆分得 tide + phase + item_id
 *   - data['subject.item_id']                → entry.item_id
 *   - data['placement.count']                → entry.count（int 或 [min,max] 区间）
 *   - data['placement.rate']                 → entry.rate（0-1 基础率）
 *   - data['selector.tides'][0]              → tide 桶 key（与 id 拆分得 tide 一致）
 *   - data['phase']                          → phase 桶 key（game_init→initial / day_refresh→refresh）
 *
 * 边界：
 * - 节点 data 缺失字段时使用默认值（rate=0.1，count=1，tide/phase 从 id 拆分）
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.2：当前运行时契约每条规则只有一个 tide）
 * - 节点 id 不匹配 idPattern 时跳过该节点（不写入任何桶）
 * - 空桶也输出（如 abyss 桶即使无条目也输出 `['initial' => [], 'refresh' => []]`）
 *
 * 集成：
 * - adapter-registry.serializeNodes 路由到本投影器（当 kind='distribution.scatter' 时）
 * - BuildView 在发布前调用本投影器生成 PublishableFile
 */

import { generatePhpFile, type PhpValue } from '../../shared/serializer/php-codegen';
import type { ResourceNode } from '../../graph/types';
import type { SerializedPhpFile } from '../../adapters/php-adapter';

/** 目标文件路径（工作区相对路径） */
const SCATTER_POOL_FILE_PATH = 'oblivions/gamedata/scatter_pool.php';

/** 作者资源 YAML 路径——用于 AUTO-GENERATED 注释 */
const SCATTER_POOL_AUTHOR_SOURCE = 'oblivions/content/distributions/scatter-pool.yaml';

/** tide 桶固定顺序——与 scatter_pool.php 文件顺序 + J-2 潮汐区主键枚举对齐 */
const TIDE_ORDER = ['shallow', 'deep', 'abyss'] as const;
type TideBucket = (typeof TIDE_ORDER)[number];

/** phase 桶固定顺序——与 scatter_pool.php 文件顺序对齐（initial 在前，refresh 在后） */
const PHASE_ORDER = ['initial', 'refresh'] as const;
type PhaseBucket = (typeof PHASE_ORDER)[number];

/** 节点 data.phase → 文件 phase key 映射 */
const PHASE_TO_FILE_KEY: Record<string, PhaseBucket> = {
  game_init: 'initial',
  day_refresh: 'refresh',
};

/** distribution.scatter 节点 id 正则——与 schema idPattern 对齐 */
const DISTRIBUTION_SCATTER_ID_PATTERN = /^(shallow|deep|abyss):(game_init|day_refresh):[a-z][a-z0-9_]*$/;

/** distribution.scatter 节点 data 期望形态 */
interface DistributionScatterData {
  'subject.item_id': string;
  'selector.tides': string[];
  'selector.regions': string[];
  'selector.excludeEntrance': boolean;
  'selector.excludeExit': boolean;
  phase: string;
  'placement.rate': number;
  'placement.count': number | [number, number];
}

/** 散落条目形态（投影回文件时的 entry 形态） */
interface ScatterEntry {
  item_id: string;
  count: number | [number, number];
  rate: number;
}

/**
 * 把 distribution.scatter 节点投影回 scatter_pool.php 形态。
 *
 * @param nodes distribution.scatter 节点数组（顺序保留为桶内条目顺序）
 * @returns 单个 SerializedPhpFile（filePath 指向 oblivions/gamedata/scatter_pool.php）
 *
 * @throws 当 selector.tides 长度 > 1 时抛错（运行时契约每条规则只有一个 tide）
 */
export function projectScatterPool(nodes: ResourceNode[]): SerializedPhpFile[] {
  const matrix = buildTidePhaseMatrix(nodes);
  const content = generatePhpFile(matrix, {
    module: 'E 游戏逻辑',
    sectionTitle: 'Oblivions 野生散落道具池',
    autoGeneratedFrom: SCATTER_POOL_AUTHOR_SOURCE,
  });
  return [{ filePath: SCATTER_POOL_FILE_PATH, content }];
}

/**
 * 把 distribution.scatter 节点按 tide × phase 矩阵分组，重建为 scatter_pool.php
 * 字典形态。
 *
 * 输出形态：`{ shallow: { initial: [...], refresh: [...] }, deep: {...}, abyss: {...} }`，
 * 每个相位列表是索引数组，数组元素是 `{item_id, count, rate}` 关联数组。
 *
 * tide 桶 key 顺序固定为 shallow → deep → abyss；phase 顺序固定为 initial → refresh。
 * 即使某桶为空也输出空数组，与原文件 3 × 2 矩阵结构对齐。
 *
 * 桶内条目顺序按节点数组顺序保留——vuedraggable 拖拽后节点顺序变化，投影器
 * 按图顺序输出，保证用户拖拽意图传递到文件。
 */
function buildTidePhaseMatrix(nodes: ResourceNode[]): PhpValue {
  // 初始化 3 × 2 矩阵为空数组
  const matrix: Record<TideBucket, Record<PhaseBucket, ScatterEntry[]>> = {
    shallow: { initial: [], refresh: [] },
    deep: { initial: [], refresh: [] },
    abyss: { initial: [], refresh: [] },
  };

  for (const node of nodes) {
    const parsed = parseDistributionScatterNode(node);
    if (parsed === null) continue;
    matrix[parsed.tide][parsed.phase].push({
      item_id: parsed.itemId,
      count: parsed.count,
      rate: parsed.rate,
    });
  }

  // 输出为 PhpValue 字典——保留 TIDE_ORDER × PHASE_ORDER 顺序
  const result: Record<string, PhpValue> = {};
  for (const tide of TIDE_ORDER) {
    const phaseDict: Record<string, PhpValue> = {};
    for (const phase of PHASE_ORDER) {
      phaseDict[phase] = matrix[tide][phase].map((entry) => ({
        item_id: entry.item_id,
        count: entry.count,
        rate: entry.rate,
      }));
    }
    result[tide] = phaseDict;
  }
  return result;
}

/**
 * 解析单个 distribution.scatter 节点，提取 tide + phase + item_id + count + rate。
 *
 * 校验：
 * - 节点 id 必须匹配 `^(shallow|deep|abyss):(game_init|day_refresh):[a-z][a-z0-9_]*$`
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.2 运行时契约）
 * - selector.tides[0] 与 id 拆分得的 tide 一致（冗余校验）
 * - data.phase 与 id 拆分得的 phase 一致（冗余校验）
 * - rate 默认 0.1，count 默认 1（与 schema default 对齐）
 *
 * @returns 解析后的 { tide, phase, itemId, count, rate }；非法节点返回 null
 */
function parseDistributionScatterNode(
  node: ResourceNode,
): {
  tide: TideBucket;
  phase: PhaseBucket;
  itemId: string;
  count: number | [number, number];
  rate: number;
} | null {
  const idMatch = DISTRIBUTION_SCATTER_ID_PATTERN.exec(node.id);
  if (!idMatch) return null;

  const tideFromId = idMatch[1] as TideBucket;
  const phaseFromId = idMatch[2] ?? '';
  const itemIdFromId = idMatch[3] ?? '';
  if (!phaseFromId || !itemIdFromId) return null;

  const phase = PHASE_TO_FILE_KEY[phaseFromId];
  if (phase === undefined) return null;

  const data = node.data as Partial<DistributionScatterData> | null;
  if (data === null || typeof data !== 'object' || Array.isArray(data)) {
    // data 非法：用 id 拆分得的最小信息构造 entry
    return { tide: tideFromId, phase, itemId: itemIdFromId, count: 1, rate: 0.1 };
  }

  // selector.tides 校验——当前运行时契约每条规则只有一个 tide
  const tides = data['selector.tides'];
  if (Array.isArray(tides) && tides.length > 1) {
    throw new Error(
      `distribution.scatter 投影失败：节点 ${node.id} 的 selector.tides 长度为 ${tides.length}，` +
        `当前运行时契约每条规则只有一个 tide（执行案 §4.2.2）`,
    );
  }

  // tide 一致性校验——id 拆分为主，selector.tides 字段在投影回写时被修正
  // 不抛错——投影器是写路径，应以 id 主键为准
  const tideFromSelector = Array.isArray(tides) && tides.length === 1 ? tides[0] : undefined;
  if (
    tideFromSelector !== undefined &&
    tideFromSelector !== tideFromId &&
    (tideFromSelector === 'shallow' || tideFromSelector === 'deep' || tideFromSelector === 'abyss')
  ) {
    // 数据漂移：以 id 拆分为主
  }

  // item_id：优先用 data['subject.item_id']，缺失时从 id 拆分
  const itemIdFromData = data['subject.item_id'];
  const finalItemId =
    typeof itemIdFromData === 'string' && itemIdFromData !== '' ? itemIdFromData : itemIdFromId;

  // rate 默认 0.1
  const rateRaw = data['placement.rate'];
  const rate = typeof rateRaw === 'number' && Number.isFinite(rateRaw) ? rateRaw : 0.1;

  // count 默认 1
  const countRaw = data['placement.count'];
  let count: number | [number, number];
  if (Array.isArray(countRaw) && countRaw.length === 2) {
    count = [Number(countRaw[0]), Number(countRaw[1])];
  } else if (typeof countRaw === 'number' && Number.isFinite(countRaw)) {
    count = countRaw;
  } else {
    count = 1;
  }

  return { tide: tideFromId, phase, itemId: finalItemId, count, rate };
}
