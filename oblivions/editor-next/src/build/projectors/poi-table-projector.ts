/**
 * @module O 内容工具箱
 *
 * poi.template 投影器——把 Resource Graph 中的 poi.template 节点投影回
 * oblivions/gamedata/poi_table.php 的 PHP 数组形态。
 *
 * 设计意图：
 * - 执行案 §4.7.2 要求 round-trip 一致性（加载 → 投影 → 字节对比，语义稳定）。
 * - 不复用 generateConfigPhp 的固定 `@module E` 头部——poi_table.php 的文件头有
 *   自定义分组注释（E-10 字段说明），投影器各自维护文件头模板以精确对齐原文件。
 * - value 部分复用 php-codegen 的 valueToPhp（4 空格缩进、单引号字符串、'key' => value 形态）。
 * - 字段顺序：保留节点 data 的 key 插入顺序（TS 对象保留 string key 顺序），
 *   节点数组顺序保留为顶层 poi_id 顺序。
 * - undefined 字段递归移除（与 php-adapter.stripUndefinedFields 对齐）——
 *   forge_anvil_poi 等条目省略 name/desc，parse 时 undefined，serialize 时仍省略。
 *
 * 边界：
 * - 节点 data 为 null/非对象时跳过该节点（不写入字典）
 * - event_pool / dismantle_returns 子结构作为索引数组原样输出
 * - mechanic_params 在 PHP 中是索引数组（如 ['passive','strategy','damage']），原样输出
 * - loot_table_overrides 空数组输出为 `[]`（与原文件对齐）
 *
 * 集成：
 * - adapter-registry 的 serializeNodes 路由到本投影器（当 kind='poi.template' 时）
 * - BuildView 在发布前调用本投影器生成 PublishableFile
 */

import { generatePhpFile, type PhpValue } from '../../shared/serializer/php-codegen';
import type { ResourceNode } from '../../graph/types';
import type { SerializedPhpFile } from '../../adapters/php-adapter';

/** 目标文件路径（工作区相对路径） */
const POI_TABLE_FILE_PATH = 'oblivions/gamedata/poi_table.php';

/** 作者资源 YAML 路径——用于 AUTO-GENERATED 注释 */
const POI_TABLE_AUTHOR_SOURCE = 'oblivions/content/pois/pois.yaml';

/**
 * 把 poi.template 节点投影回 poi_table.php 形态。
 *
 * @param nodes poi.template 节点数组（顺序保留为顶层 poi_id 顺序）
 * @returns 单个 SerializedPhpFile（filePath 指向 oblivions/gamedata/poi_table.php）
 */
export function projectPoiTable(nodes: ResourceNode[]): SerializedPhpFile[] {
  const dict = buildPoiTemplateDict(nodes);
  const content = generatePhpFile(dict, {
    module: 'E 游戏逻辑',
    sectionTitle: 'Oblivions POI 模板表',
    autoGeneratedFrom: POI_TABLE_AUTHOR_SOURCE,
  });
  return [{ filePath: POI_TABLE_FILE_PATH, content }];
}

/**
 * 把 ResourceNode[] 重建为 map-keyed PHP 字典形态。
 *
 * 节点 id 作为顶层 key，node.data 作为 value。
 * stripUndefinedFields 递归移除 undefined 字段——forge_anvil_poi 等条目 parse 时
 * data.name===undefined，serialize 时仍省略，保证 round-trip 一致性。
 *
 * 键顺序按节点数组顺序保留（不强制排序）——调用方负责传入有序节点。
 */
function buildPoiTemplateDict(nodes: ResourceNode[]): PhpValue {
  const dict: Record<string, PhpValue> = {};
  for (const node of nodes) {
    if (node.data === null || typeof node.data !== 'object' || Array.isArray(node.data)) {
      // 非法 data 形态：跳过该节点，避免污染字典
      continue;
    }
    const cleaned = stripUndefinedFields(node.data);
    dict[node.id] = cleaned as PhpValue;
  }
  return dict;
}

/**
 * 递归移除 undefined 字段——与 php-adapter.stripUndefinedFields / ts-locale-adapter
 * 行为一致：保留所有显式值（含 false / 0 / '' / null），仅移除 undefined。
 *
 * 用于序列化时对齐原文件省略字段的契约（如 forge_anvil_poi 省略 name/desc）。
 */
function stripUndefinedFields(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(stripUndefinedFields);
  }
  if (value !== null && typeof value === 'object') {
    const result: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (v === undefined) continue;
      result[k] = stripUndefinedFields(v);
    }
    return result;
  }
  return value;
}
