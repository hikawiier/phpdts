/**
 * @module O 内容工具箱
 *
 * loot.table 投影器——把 Resource Graph 中的 loot.table 节点投影回
 * oblivions/gamedata/loot_tables.php 的 PHP 数组形态。
 *
 * 设计意图：
 * - 执行案 §4.7.2 要求保留分组注释、表 ID 顺序。
 * - 三层嵌套结构（表 → groups[] → entries[]）由 valueToPhp 递归输出，无需特殊处理。
 * - count 多态：int 输出为数字，[min,max] 输出为索引数组——parsePhpArray 解析时
 *   `count => 1` 得 number，`count => [1, 3]` 得 number[]，valueToPhp 已正确处理两种形态。
 * - 文件头 `@module F 物品系统` 与原文件对齐（区别于 poi_table.php 的 @module E）。
 * - 表 ID 顺序按节点数组顺序保留（不强制排序）——调用方负责传入有序节点。
 *
 * 边界：
 * - 节点 data 为 null/非对象时跳过该节点
 * - groups 空数组输出为 `[]`（empty_loot 表的合法形态）
 * - entries 中的 weight 默认 1，但投影器不补充默认值——保留 node.data 原样
 *   （parse 时已读取全部字段，schema 默认值仅用于新建节点）
 *
 * 集成：
 * - adapter-registry.serializeNodes 路由到本投影器（当 kind='loot.table' 时）
 * - BuildView 在发布前调用本投影器生成 PublishableFile
 */

import { generatePhpFile, type PhpValue } from '../../shared/serializer/php-codegen';
import type { ResourceNode } from '../../graph/types';
import type { SerializedPhpFile } from '../../adapters/php-adapter';

/** 目标文件路径（工作区相对路径） */
const LOOT_TABLE_FILE_PATH = 'oblivions/gamedata/loot_tables.php';

/** 作者资源 YAML 路径——用于 AUTO-GENERATED 注释 */
const LOOT_TABLE_AUTHOR_SOURCE = 'oblivions/content/loot-tables/loot-tables.yaml';

/**
 * 把 loot.table 节点投影回 loot_tables.php 形态。
 *
 * @param nodes loot.table 节点数组（顺序保留为顶层 table_id 顺序）
 * @returns 单个 SerializedPhpFile（filePath 指向 oblivions/gamedata/loot_tables.php）
 */
export function projectLootTable(nodes: ResourceNode[]): SerializedPhpFile[] {
  const dict = buildLootTableDict(nodes);
  const content = generatePhpFile(dict, {
    module: 'F 物品系统',
    sectionTitle: 'Oblivions 战利品表（F-4 引擎配置）',
    autoGeneratedFrom: LOOT_TABLE_AUTHOR_SOURCE,
  });
  return [{ filePath: LOOT_TABLE_FILE_PATH, content }];
}

/**
 * 把 ResourceNode[] 重建为 map-keyed PHP 字典形态。
 *
 * 节点 id 作为顶层 key（表 ID），node.data 作为 value（含 name / durability_decay / groups）。
 * stripUndefinedFields 递归移除 undefined 字段。
 *
 * 三层嵌套（groups → entries）由 valueToPhp 递归处理，无需特殊代码。
 * count 多态由 TS 数据原样保留（number 或 number[]），valueToPhp 已正确输出。
 */
function buildLootTableDict(nodes: ResourceNode[]): PhpValue {
  const dict: Record<string, PhpValue> = {};
  for (const node of nodes) {
    if (node.data === null || typeof node.data !== 'object' || Array.isArray(node.data)) {
      continue;
    }
    const cleaned = stripUndefinedFields(node.data);
    dict[node.id] = cleaned as PhpValue;
  }
  return dict;
}

/**
 * 递归移除 undefined 字段——与 php-adapter.stripUndefinedFields 行为一致。
 *
 * 保留所有显式值（含 false / 0 / '' / null），仅移除 undefined。
 * 用于序列化时对齐原文件省略字段的契约。
 */
function stripUndefinedFields(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(stripUndefinedFields);
  }
  if (value !== null && typeof value === 'object') {
    const result: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (v === undefined) continue;
      result[k] = stripUndefinedFields(v);
    }
    return result;
  }
  return value;
}
