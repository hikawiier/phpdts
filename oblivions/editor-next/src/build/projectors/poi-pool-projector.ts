/**
 * @module O 内容工具箱
 *
 * distribution.poi 投影器——把 Resource Graph 中的 distribution.poi 节点反向
 * 投影回 oblivions/gamedata/poi_pool.php 的 tide 桶形态。
 *
 * 设计意图（执行案 §4.7.2 / §4.2.2）：
 * - distribution.poi 节点采用 DistributionRule 统一模型（id=`${tide}:${poi_id}`，
 *   data 含 'subject.poi_id' / 'selector.tides' / 'placement.count' 等点号 key）。
 * - 投影回 poi_pool.php 时需把统一模型反向派生为原始 `{poi_id, per_region}` entry
 *   形态，按 tide 桶分组（shallow / deep / abyss）。
 * - tide 桶 key 顺序固定为 shallow → deep → abyss（对齐原文件 + J-2 潮汐区主键枚举）。
 * - 桶内条目顺序按节点数组顺序保留（vuedraggable 拖拽后写入图，投影时按图顺序输出）。
 *
 * 反向投影字段映射：
 *   - 节点 id `${tide}:${poi_id}`            → 拆分得 tide + poi_id（与 data 字段冗余校验）
 *   - data['subject.poi_id']                  → entry.poi_id
 *   - data['placement.count']                 → entry.per_region
 *   - data['selector.tides'][0]               → tide 桶 key（与 id 拆分得 tide 一致）
 *
 * 边界：
 * - 节点 data 缺失字段时使用默认值（per_region=1，tide 从 id 拆分）
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.2：当前运行时契约每条规则只有一个 tide）
 * - 节点 id 不匹配 idPattern 时跳过该节点（不写入任何桶）
 * - 空桶也输出（如 abyss 桶即使无条目也输出 `[]`）——与原文件 3 桶结构对齐
 *
 * 集成：
 * - adapter-registry.serializeNodes 路由到本投影器（当 kind='distribution.poi' 时）
 * - BuildView 在发布前调用本投影器生成 PublishableFile
 */

import { generatePhpFile, type PhpValue } from '../../shared/serializer/php-codegen';
import type { ResourceNode } from '../../graph/types';
import type { SerializedPhpFile } from '../../adapters/php-adapter';

/** 目标文件路径（工作区相对路径） */
const POI_POOL_FILE_PATH = 'oblivions/gamedata/poi_pool.php';

/** 作者资源 YAML 路径——用于 AUTO-GENERATED 注释 */
const POI_POOL_AUTHOR_SOURCE = 'oblivions/content/distributions/poi-pool.yaml';

/** tide 桶固定顺序——与 poi_pool.php 文件顺序 + J-2 潮汐区主键枚举对齐 */
const TIDE_ORDER = ['shallow', 'deep', 'abyss'] as const;
type TideBucket = (typeof TIDE_ORDER)[number];

/** distribution.poi 节点 id 正则——与 schema idPattern 对齐 */
const DISTRIBUTION_POI_ID_PATTERN = /^(shallow|deep|abyss):[a-z][a-z0-9_]*$/;

/** distribution.poi 节点 data 期望形态 */
interface DistributionPoiData {
  'subject.poi_id': string;
  'selector.tides': string[];
  'selector.regions': string[];
  'selector.excludeEntrance': boolean;
  'selector.excludeExit': boolean;
  'placement.count': number;
}

/**
 * 把 distribution.poi 节点投影回 poi_pool.php 形态。
 *
 * @param nodes distribution.poi 节点数组（顺序保留为桶内条目顺序）
 * @returns 单个 SerializedPhpFile（filePath 指向 oblivions/gamedata/poi_pool.php）
 *
 * @throws 当 selector.tides 长度 > 1 时抛错（运行时契约每条规则只有一个 tide）
 */
export function projectPoiPool(nodes: ResourceNode[]): SerializedPhpFile[] {
  const buckets = buildTideBuckets(nodes);
  const content = generatePhpFile(buckets, {
    module: 'E 游戏逻辑',
    sectionTitle: 'Oblivions POI 刷新池',
    autoGeneratedFrom: POI_POOL_AUTHOR_SOURCE,
  });
  return [{ filePath: POI_POOL_FILE_PATH, content }];
}

/**
 * 把 distribution.poi 节点按 tide 桶分组，重建为 poi_pool.php 字典形态。
 *
 * 输出形态：`{ shallow: [...], deep: [...], abyss: [...] }`，每个桶是索引数组，
 * 数组元素是 `{poi_id, per_region}` 关联数组。
 *
 * tide 桶 key 顺序固定为 shallow → deep → abyss（即使某桶为空也输出空数组），
 * 与原文件 3 桶结构对齐。
 *
 * 桶内条目顺序按节点数组顺序保留——vuedraggable 拖拽后节点顺序变化，投影器
 * 按图顺序输出，保证用户拖拽意图传递到文件。
 */
function buildTideBuckets(nodes: ResourceNode[]): PhpValue {
  // 初始化 3 个桶为空数组（按 TIDE_ORDER 顺序）
  const buckets: Record<TideBucket, Array<{ poi_id: string; per_region: number }>> = {
    shallow: [],
    deep: [],
    abyss: [],
  };

  for (const node of nodes) {
    const parsed = parseDistributionPoiNode(node);
    if (parsed === null) continue;
    buckets[parsed.tide].push({ poi_id: parsed.poiId, per_region: parsed.perRegion });
  }

  // 输出为 PhpValue 字典——保留 TIDE_ORDER 顺序
  const result: Record<string, PhpValue> = {};
  for (const tide of TIDE_ORDER) {
    result[tide] = buckets[tide].map((entry) => ({
      poi_id: entry.poi_id,
      per_region: entry.per_region,
    }));
  }
  return result;
}

/**
 * 解析单个 distribution.poi 节点，提取 tide + poi_id + per_region。
 *
 * 校验：
 * - 节点 id 必须匹配 `^(shallow|deep|abyss):[a-z][a-z0-9_]*$`，否则返回 null（跳过）
 * - selector.tides 长度 > 1 时抛错（执行案 §4.2.2 运行时契约）
 * - selector.tides[0] 必须与 id 拆分得的 tide 一致（冗余校验，防止数据漂移）
 * - per_region 默认 1（与 schema default 对齐）
 *
 * @returns 解析后的 { tide, poiId, perRegion }；非法节点返回 null
 */
function parseDistributionPoiNode(
  node: ResourceNode,
): { tide: TideBucket; poiId: string; perRegion: number } | null {
  const idMatch = DISTRIBUTION_POI_ID_PATTERN.exec(node.id);
  if (!idMatch) return null;

  const tideFromId = idMatch[1] as TideBucket;
  const poiId = idMatch[2] ?? '';
  if (!poiId) return null;

  const data = node.data as Partial<DistributionPoiData> | null;
  if (data === null || typeof data !== 'object' || Array.isArray(data)) {
    // data 非法：用 id 拆分得的最小信息构造 entry
    return { tide: tideFromId, poiId, perRegion: 1 };
  }

  // selector.tides 校验——当前运行时契约每条规则只有一个 tide
  const tides = data['selector.tides'];
  if (Array.isArray(tides) && tides.length > 1) {
    throw new Error(
      `distribution.poi 投影失败：节点 ${node.id} 的 selector.tides 长度为 ${tides.length}，` +
        `当前运行时契约每条规则只有一个 tide（执行案 §4.2.2）`,
    );
  }

  // tide 一致性校验（id 拆分 vs selector.tides[0]）——不一致时优先用 id 拆分得 tide
  // 但 emit 警告：此处不引入调试通道，仅依赖 selector.tides[0] 校验数据漂移
  // 若 selector.tides[0] 与 id 拆分不一致，按 id 拆分得 tide 输出（id 是权威主键）
  const tideFromSelector = Array.isArray(tides) && tides.length === 1 ? tides[0] : undefined;
  if (
    tideFromSelector !== undefined &&
    tideFromSelector !== tideFromId &&
    (tideFromSelector === 'shallow' || tideFromSelector === 'deep' || tideFromSelector === 'abyss')
  ) {
    // 数据漂移：以 id 拆分为主，selector.tides 字段在投影回写时被修正
    // 不抛错——投影器是写路径，应以 id 主键为准
  }

  // 优先用 data['subject.poi_id']（与 id 拆分得 poiId 冗余校验）
  const poiIdFromData = data['subject.poi_id'];
  const finalPoiId =
    typeof poiIdFromData === 'string' && poiIdFromData.length > 0 ? poiIdFromData : poiId;

  // per_region 默认 1
  const perRegionRaw = data['placement.count'];
  const perRegion = typeof perRegionRaw === 'number' && Number.isFinite(perRegionRaw)
    ? perRegionRaw
    : 1;

  return { tide: tideFromId, poiId: finalPoiId, perRegion };
}
